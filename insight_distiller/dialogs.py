"""Split the paste into the five broadcast dialogues and keep each show's points.

A sentence is kept only when its anchor phrases sit inside that show's slice,
so a quick-comment number cannot be credited to a YouTube talk.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Dialogue:
    key: str
    title: str
    items: list[str] = field(default_factory=list)


def _between(text: str, start: str, end: str | None) -> str:
    i = text.find(start)
    if i < 0:
        return ""
    if end is None:
        return text[i:]
    j = text.find(end, i + len(start))
    if j < 0:
        return text[i:]
    return text[i:j]


def _add(blob: str, items: list[str], needles: tuple[str, ...], sentence: str) -> None:
    if blob and all(needle in blob for needle in needles):
        items.append(sentence)


def dialogues(text: str) -> list[Dialogue]:
    shows = [
        _lee(text),
        _yeolmae(text),
        _jiwon(text),
        _yun(text),
        _hyojin(text),
        _nokun(text),
        _park(text),
        _kcg(text),
        _rts(text),
        _shin(text),
    ]
    return [show for show in shows if show.items]


