def checks() -> dict:
    """원문 숫자를 식으로 닫는다. 새 추정은 없다."""
    hbm_good, dram_good = 7, 9
    wafers_per_hbm = dram_good / hbm_good
    capex_bn = 800.0
    mem_old, mem_now = 0.10, 0.30
    krw_for_1000jo = 1_000 / capex_bn * 1_000  # 8,000억 달러가 1,000조가 되는 환율
    kosdaq_low, kosdaq_now = 620, 910
    kosdaq_up = kosdaq_now / kosdaq_low - 1
    consensus_all, consensus_recent = 108.1, 106.0
    fx_if_100jo_is_78bn = 100e12 / 78e9
    gm, opm = 0.82, 0.76
    hbm3_sk, hbm4_sk, hbm4_sec, hbm4_mu = 0.85, 0.52, 0.30, 0.18
    jeju_h1 = 600 + 1_200
    kolmar_sales, kolmar_op = 0.221, 0.577

    assert abs(wafers_per_hbm - 9 / 7) < 1e-9
    assert abs(capex_bn * mem_old - 80) < 1e-9
    assert abs(capex_bn * mem_now - 240) < 1e-9
    assert abs(krw_for_1000jo - 1250) < 1e-6
    assert abs(kosdaq_up - (910 / 620 - 1)) < 1e-12
    assert abs(fx_if_100jo_is_78bn - 1282.05) < 0.1
    assert abs((gm - opm) - 0.06) < 1e-9
    assert hbm3_sk + 0.15 == 1
    assert 0.50 <= hbm4_sk <= 0.55
    assert jeju_h1 == 1_800
    assert kolmar_op > kolmar_sales

    return {
        "wafers_per_hbm": wafers_per_hbm,
        "mem_old_bn": capex_bn * mem_old,
        "mem_now_bn": capex_bn * mem_now,
        "fx_1000jo": krw_for_1000jo,
        "kosdaq_up": kosdaq_up,
        "consensus_cut": consensus_recent / consensus_all - 1,
        "fx_78bn": fx_if_100jo_is_78bn,
        "opex_pp": (gm - opm) * 100,
    }


