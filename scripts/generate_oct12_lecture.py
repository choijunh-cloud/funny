def verify(path: Path):
    doc = Document(str(path))
    chunks: list[str] = []
    for p in doc.paragraphs:
        if p.text.strip():
            chunks.append(p.text.strip())
    for table in doc.tables:
        for row in table.rows:
            cells = [c.text.strip() for c in row.cells]
            if any(cells):
                chunks.append(" | ".join(cells))
    blob = "\n".join(chunks)
    required = [
        "화자가 심으려는 말",
        "하려는 말",
        "레임덕",
        "자산주",
        "주성엔지니어링",
        "베어 스티프닝",
        "오퍼레이션 트위스트",
        "금산법",
        "Goltens",
        "6,400",
        "1조 달러",
        "릭 라이더",
        "3.0~3.1배",
        "24.5만 원",
        "Wärtsilä",
        "720억 달러",
        "1,200억 달러",
        "110조",
        "15배",
        "31만 원",
        "솔리다임",
        "8.6만 원",
        "투자 권유가 아닙니다",
    ]
    missing = [k for k in required if k not in blob]
    if missing:
        raise SystemExit(f"verify failed, missing: {missing}")
    if len(doc.tables) < 15:
        raise SystemExit(f"verify failed, tables={len(doc.tables)}")
    print(f"verify ok: paragraphs={len(doc.paragraphs)} tables={len(doc.tables)} chars={len(blob)}")


